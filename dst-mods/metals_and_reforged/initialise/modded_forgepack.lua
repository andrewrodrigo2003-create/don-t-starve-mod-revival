local function d(b)
    local c = b.prefab:upper()
    if
        _G.TUNING.THE_FORGE_ITEM_PACK[c] and _G.TUNING.THE_FORGE_ITEM_PACK[c].DURABILITY and
            _G.TUNING.THE_FORGE_ITEM_PACK[c].DURABILITY.AMOUNT
     then
        if _G.TUNING.THE_FORGE_ITEM_PACK[c].DURABILITY.AMOUNT > 0 then
            b:AddComponent("finiteuses")
            b.components.finiteuses:SetMaxUses(_G.TUNING.THE_FORGE_ITEM_PACK[c].DURABILITY.AMOUNT)
            b.components.finiteuses:SetUses(_G.TUNING.THE_FORGE_ITEM_PACK[c].DURABILITY.AMOUNT)
            b.components.finiteuses:SetOnFinished(b.Remove)
            if _G.TUNING.THE_FORGE_ITEM_PACK[c].DURABILITY.CONSUMPTION_NORMAL then
                b.components.finiteuses:SetConsumption(
                    ACTIONS.ATTACK,
                    _G.TUNING.THE_FORGE_ITEM_PACK[c].DURABILITY.CONSUMPTION_NORMAL
                )
            end
            if _G.TUNING.THE_FORGE_ITEM_PACK[c].DURABILITY.CONSUMPTION_SPECIAL then
                b.components.finiteuses:SetConsumption(
                    ACTIONS.CASTAOE,
                    _G.TUNING.THE_FORGE_ITEM_PACK[c].DURABILITY.AMOUNT *
                        _G.TUNING.THE_FORGE_ITEM_PACK[c].DURABILITY.CONSUMPTION_SPECIAL /
                        100
                )
            end
            if b:HasTag("hide_percentage") then
                b:RemoveTag("hide_percentage")
            end
        end
    else
        print("Cannot find tunning for " .. c)
    end
end

