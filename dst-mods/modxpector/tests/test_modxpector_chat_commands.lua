local ROOT = os.getenv("DST_RUNTIME_ROOT") or "."
local Commands = dofile(ROOT .. "/dst-mods/modxpector/scripts/modxpector/chat_commands.lua")
local parsed = Commands.Parse("/mx analisar")
assert(parsed.kind == "analyze")
parsed = Commands.Parse("  !MX ANALISAR MODS  ")
assert(parsed.kind == "analyze")
assert(Commands.Parse("/mx status").kind == "status")
assert(Commands.Parse("/mx parar").kind == "stop")
assert(Commands.Parse("/mx ajuda").kind == "help")
assert(Commands.Parse("/mx testar").kind == "list_suites")
parsed = Commands.Parse("/mx testar friendly_skeleton_servant_smoke approach_existing_servant")
assert(parsed.kind == "run_suite" and parsed.suite_id == "friendly_skeleton_servant_smoke"
    and parsed.scenario_id == "approach_existing_servant")
assert(Commands.Parse("/mx testar bad/id scenario").kind == "invalid")
assert(Commands.Parse("/mx apagar_mundo").kind == "invalid")
assert(Commands.Parse("/mx analisar; spawn_prefab('deerclops')").kind == "invalid")
assert(Commands.Parse(string.rep("x", 257)) == nil)
assert(Commands.Parse("hello everyone") == nil)
print("ModXpector chat command parser tests passed.")
